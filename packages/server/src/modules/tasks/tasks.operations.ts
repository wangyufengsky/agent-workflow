import {
  acceptNodeOp,
  cancelTaskOp,
  confirmPlanOp,
  createTaskOp,
  decideRequirementOp,
  deleteProjectOp,
  deleteRoleOp,
  deleteWorkflowOp,
  deliverTaskOp,
  getAgentsMdOp,
  getNodeOp,
  getRequirementsOp,
  getTaskOp,
  getTaskTimelineOp,
  listPreviewSessionsOp,
  listTasksOp,
  nodeDiffFileOp,
  nodeDiffOp,
  pauseTaskOp,
  rejectNodeOp,
  replaceRequirementsOp,
  replanOp,
  requestChangesOp,
  resolveInboxOp,
  resumeTaskOp,
  retryNodeOp,
  retryTaskOp,
  reverifyRequirementsOp,
  reviewCommentsOp,
  reviseFromReviewOp,
  saveDraftPlanOp,
  skipCheckOp,
  skipNodeOp,
  startAgentsMdTaskOp,
  startTaskOp,
  taskDiffFileOp,
  taskDiffOp,
  updateCheckCommandOp,
} from '@aw/shared';
import { implement } from '../../core/operations/operations.ts';
import type { TasksService } from './tasks.service.ts';

export function tasksOperations(tasks: TasksService) {
  return [
    implement(listTasksOp, (query) => tasks.list(query)),
    implement(listPreviewSessionsOp, ({ id }) => tasks.previewSessions(id)),
    implement(createTaskOp, (input) => tasks.create(input)),
    implement(getAgentsMdOp, ({ id }) => tasks.agentsMd(id)),
    implement(startAgentsMdTaskOp, (input) => tasks.createAgentsMdTask(input)),
    implement(getTaskOp, ({ id }) => tasks.detail(id)),
    implement(getRequirementsOp, ({ id }) => tasks.requirements(id)),
    implement(replaceRequirementsOp, ({ id, items }) => tasks.replaceRequirements(id, items)),
    implement(decideRequirementOp, ({ id, itemId, conclusion, note }) =>
      tasks.decideRequirement(id, itemId, { conclusion, note }),
    ),
    implement(reverifyRequirementsOp, ({ id }) => tasks.reverifyRequirements(id)),
    implement(getTaskTimelineOp, ({ id, afterId }) => ({ items: tasks.timeline(id, afterId) })),
    implement(startTaskOp, ({ id }) => tasks.start(id)),
    implement(retryTaskOp, ({ id, feedback }) => tasks.retry(id, feedback)),
    implement(updateCheckCommandOp, ({ id, command, updateProject }) =>
      tasks.updateCheckCommand(id, command, updateProject),
    ),
    implement(skipCheckOp, ({ id }) => tasks.skipCheck(id)),
    implement(cancelTaskOp, ({ id, keepBranch }) => tasks.cancel(id, keepBranch ?? false)),
    implement(confirmPlanOp, ({ id, version }) => tasks.confirmPlan(id, version)),
    implement(replanOp, ({ id, feedback }) => tasks.replan(id, feedback)),
    implement(saveDraftPlanOp, ({ id, baseVersion, graph }) => tasks.saveDraftPlan(id, baseVersion, graph)),
    implement(pauseTaskOp, ({ id }) => tasks.pause(id)),
    implement(resumeTaskOp, ({ id }) => tasks.resume(id)),
    implement(getNodeOp, ({ id, nodeId }) => tasks.node(id, nodeId)),
    implement(acceptNodeOp, ({ id, nodeId }) => tasks.acceptNode(id, nodeId)),
    implement(rejectNodeOp, ({ id, nodeId, feedback }) => tasks.rejectNode(id, nodeId, feedback)),
    implement(skipNodeOp, ({ id, nodeId }) => tasks.skipNode(id, nodeId)),
    implement(retryNodeOp, ({ id, nodeId, feedback }) => tasks.retryNode(id, nodeId, feedback)),
    implement(deliverTaskOp, ({ id, ...request }) => tasks.deliver(id, request)),
    implement(requestChangesOp, ({ id, reason, feedback, attachmentIds, page }) =>
      tasks.requestChanges(id, reason, feedback, attachmentIds, page),
    ),
    implement(reviewCommentsOp, ({ id }) => tasks.reviewComments(id)),
    implement(reviseFromReviewOp, ({ id, commentIds, note }) => tasks.reviseFromReview(id, commentIds, note)),
    implement(taskDiffOp, ({ id }) => tasks.diff(id)),
    implement(taskDiffFileOp, ({ id, path }) => tasks.diffFile(id, path)),
    implement(nodeDiffOp, ({ id, nodeId }) => tasks.nodeDiff(id, nodeId)),
    implement(nodeDiffFileOp, ({ id, nodeId, path }) => tasks.nodeDiffFile(id, nodeId, path)),
    implement(resolveInboxOp, ({ id, response }) => tasks.resolveInbox(id, response)),
    implement(deleteProjectOp, ({ id }) => tasks.deleteProject(id)),
    implement(deleteWorkflowOp, ({ key }) => tasks.deleteWorkflow(key)),
    implement(deleteRoleOp, ({ id }) => tasks.deleteRole(id)),
  ];
}
