import {
  acceptNodeOp,
  archiveFinishedTasksOp,
  archiveTaskOp,
  cancelTaskOp,
  confirmPlanOp,
  createBrowserCaseOp,
  createTaskOp,
  decideRequirementOp,
  deleteProjectOp,
  deleteRoleOp,
  deleteTaskOp,
  deleteWorkflowOp,
  deliverTaskOp,
  finishFrontendTaskOp,
  getAgentsMdOp,
  getNodeOp,
  getRequirementHistoryOp,
  getRequirementsOp,
  getTaskArtifactOp,
  getTaskDocumentDraftOp,
  getTaskOp,
  getTaskTimelineOp,
  listBrowserCasesOp,
  listPreviewSessionsOp,
  listTasksOp,
  nodeDiffFileOp,
  nodeDiffOp,
  pauseTaskOp,
  previewConventionEvidenceOp,
  refreshDeliveryStatusOp,
  rejectNodeOp,
  replaceRequirementsOp,
  replanOp,
  requestChangesOp,
  rerunBrowserCaseOp,
  resolveInboxOp,
  resumeTaskOp,
  retryNodeOp,
  retryTaskOp,
  reverifyRequirementsOp,
  reviewCommentsOp,
  reviseFromReviewOp,
  reviseTaskArtifactOp,
  runBrowserCaseOp,
  saveDraftPlanOp,
  skipCheckOp,
  skipNodeOp,
  startAgentsMdTaskOp,
  startTaskOp,
  taskCheckEvidenceOp,
  taskDiffFileOp,
  taskDiffOp,
  unarchiveTaskOp,
  updateBrowserCaseOp,
  updateCheckCommandOp,
} from '@aw/shared';
import { implement } from '../../core/operations/operations.ts';
import type { TasksService } from './tasks.service.ts';

export function tasksOperations(tasks: TasksService) {
  return [
    implement(listTasksOp, (query) => tasks.list(query)),
    implement(listPreviewSessionsOp, ({ id }) => tasks.previewSessions(id)),
    implement(listBrowserCasesOp, ({ projectId }) => ({ items: tasks.browserCases.list(projectId) })),
    implement(createBrowserCaseOp, ({ projectId, definition }) => tasks.browserCases.create(projectId, definition)),
    implement(updateBrowserCaseOp, ({ projectId, caseId, revision, definition }) =>
      tasks.browserCases.update(projectId, caseId, revision, definition),
    ),
    implement(runBrowserCaseOp, ({ projectId, caseId, revision }) => tasks.runBrowserCase(projectId, caseId, revision)),
    implement(rerunBrowserCaseOp, ({ id }) => tasks.rerunBrowserCase(id)),
    implement(createTaskOp, (input) => tasks.create(input)),
    implement(getAgentsMdOp, ({ id }) => tasks.agentsMd(id)),
    implement(startAgentsMdTaskOp, (input) => tasks.createAgentsMdTask(input)),
    implement(previewConventionEvidenceOp, (input) => tasks.previewConventionEvidence(input)),
    implement(getTaskOp, ({ id }) => tasks.workbenchDetail(id)),
    implement(getTaskDocumentDraftOp, async ({ id, nodeId }) => ({ draft: await tasks.documentDraft(id, nodeId) })),
    implement(getTaskArtifactOp, ({ id, versionId, sheet }) => tasks.artifacts.preview(id, versionId, sheet)),
    implement(reviseTaskArtifactOp, (input) => tasks.reviseArtifact(input)),
    implement(getRequirementsOp, ({ id }) => tasks.requirements(id)),
    implement(getRequirementHistoryOp, ({ id, revisionId }) => tasks.requirementHistory(id, revisionId)),
    implement(replaceRequirementsOp, ({ id, items }) => tasks.replaceRequirements(id, items)),
    implement(decideRequirementOp, ({ id, itemId, conclusion, note }) =>
      tasks.decideRequirement(id, itemId, { conclusion, note }),
    ),
    implement(reverifyRequirementsOp, ({ id, revisionId, expectedCommitSha, items }) =>
      tasks.reverifyRequirements(id, revisionId, expectedCommitSha, items),
    ),
    implement(getTaskTimelineOp, ({ id, afterId }) => ({ items: tasks.timeline(id, afterId) })),
    implement(startTaskOp, ({ id }) => tasks.start(id)),
    implement(retryTaskOp, ({ id, feedback }) => tasks.retry(id, feedback)),
    implement(updateCheckCommandOp, ({ id, command, updateProject, expectedCommand }) =>
      tasks.updateCheckCommand(id, command, updateProject, expectedCommand),
    ),
    implement(skipCheckOp, ({ id }) => tasks.skipCheck(id)),
    implement(cancelTaskOp, ({ id, keepBranch }) => tasks.cancel(id, keepBranch ?? false)),
    implement(archiveTaskOp, ({ id }) => tasks.archive(id)),
    implement(unarchiveTaskOp, ({ id }) => tasks.unarchive(id)),
    implement(archiveFinishedTasksOp, (input) => tasks.archiveFinished(input)),
    implement(deleteTaskOp, ({ id }) => tasks.delete(id)),
    implement(confirmPlanOp, ({ id, version }) => tasks.confirmPlan(id, version)),
    implement(replanOp, ({ id, feedback }) => tasks.replan(id, feedback)),
    implement(saveDraftPlanOp, ({ id, baseVersion, graph }) => tasks.saveDraftPlan(id, baseVersion, graph)),
    implement(pauseTaskOp, ({ id }) => tasks.pause(id)),
    implement(resumeTaskOp, ({ id }) => tasks.resume(id)),
    implement(getNodeOp, ({ id, nodeId }) => tasks.node(id, nodeId)),
    implement(acceptNodeOp, ({ id, nodeId }) => tasks.acceptNode(id, nodeId)),
    implement(rejectNodeOp, ({ id, nodeId, feedback }) => tasks.rejectNode(id, nodeId, feedback)),
    implement(skipNodeOp, ({ id, nodeId }) => tasks.skipNode(id, nodeId)),
    implement(retryNodeOp, ({ id, nodeId, feedback }) => tasks.retryNode(id, nodeId, feedback)),
    implement(deliverTaskOp, ({ id, ...request }) => tasks.deliver(id, request)),
    implement(requestChangesOp, ({ id, reason, feedback, attachmentIds, page }) =>
      tasks.requestChanges(id, reason, feedback, attachmentIds, page),
    ),
    implement(finishFrontendTaskOp, ({ id, path }) => tasks.finishFrontend(id, path)),
    implement(refreshDeliveryStatusOp, ({ id }) => tasks.refreshDeliveryStatus(id)),
    implement(reviewCommentsOp, ({ id }) => tasks.reviewComments(id)),
    implement(reviseFromReviewOp, ({ id, commentIds, note }) => tasks.reviseFromReview(id, commentIds, note)),
    implement(taskCheckEvidenceOp, ({ id, evidenceId }) => tasks.checkEvidence(id, evidenceId)),
    implement(taskDiffOp, ({ id }) => tasks.diff(id)),
    implement(taskDiffFileOp, ({ id, path }) => tasks.diffFile(id, path)),
    implement(nodeDiffOp, ({ id, nodeId }) => tasks.nodeDiff(id, nodeId)),
    implement(nodeDiffFileOp, ({ id, nodeId, path }) => tasks.nodeDiffFile(id, nodeId, path)),
    implement(resolveInboxOp, ({ id, response }) => tasks.resolveInbox(id, response)),
    implement(deleteProjectOp, ({ id }) => tasks.deleteProject(id)),
    implement(deleteWorkflowOp, ({ key }) => tasks.deleteWorkflow(key)),
    implement(deleteRoleOp, ({ id }) => tasks.deleteRole(id)),
  ];
}
